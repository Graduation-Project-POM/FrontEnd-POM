import { useState } from "react";
import {
  Box,
  Typography,
  Card,
  CardContent,
  Button,
  Container,
  Chip,
  Stack,
} from "@mui/material";
import { useTranslation } from "react-i18next";
import { ExternalLink } from "lucide-react";
import i18n from "../../../utils/i18n";
import { styles } from "./worksheets";

export default function Worksheets() {
  const { t } = useTranslation();
  const isRTL = i18n.language === "ar";
  const [activeFilter, setActiveFilter] = useState("All");

  const directorates = [
    "All",
    ...new Set(worksheets.map((w) => w.directorate)),
  ];
  const filtered =
    activeFilter === "All"
      ? worksheets
      : worksheets.filter((w) => w.directorate === activeFilter);

  return (
    <Box sx={styles.page(isRTL)}>
      <Container maxWidth="xl">
        {/* Hero */}
        <Box textAlign="center" mb={8}>
          <Typography variant="h2" sx={styles.heroTitle}>
            {t("sheets.heroTitle")}
          </Typography>
          <Typography variant="h6" sx={styles.heroDesc}>
            {t("sheets.heroDesc")}
          </Typography>
        </Box>

        {/* Filters */}
        <Stack
          direction="row"
          spacing={2.6}
          rowGap={2.6} 
          flexWrap="wrap"
          justifyContent="center"
          sx={{ mb: 6 }}
        >
          {directorates.map((dir) => (
            <Chip
              key={dir}
              label={
                dir === "All"
                  ? t("common.all")
                  : t(`sheets.directorates.${dir}`)
              }
              onClick={() => setActiveFilter(dir)}
              sx={styles.filterChip(activeFilter === dir)}
            />
          ))}
        </Stack>
        <Box
          sx={{
            display: "grid",
            gap: 3,
            gridTemplateColumns: {
              xs: "1fr",
              sm: "repeat(auto-fill, minmax(320px, 1fr))",
            },
          }}
        >
          {filtered.map((w) => (
            <Card key={w.link} sx={styles.card(w.directorate)}>
              <CardContent sx={styles.cardContent}>
                <Box sx={styles.iconBox(w.directorate)}>{w.icon}</Box>

                <Chip
                  label={t(`sheets.directorates.${w.directorate}`)}
                  size="small"
                  sx={styles.directorateChip(w.directorate)}
                />

                <Typography variant="h6" sx={styles.title}>
                  {t(w.title)}
                </Typography>

                <Typography variant="body2" sx={styles.description}>
                  {t(w.description)}
                </Typography>

                <Button
                  href={w.link}
                  target="_blank"
                  rel="noopener noreferrer"
                  variant="contained"
                  fullWidth
                  endIcon={<ExternalLink size={18} />}
                  sx={styles.button(w.directorate)}
                >
                  {t("sheets.open")}
                </Button>
              </CardContent>
            </Card>
          ))}
        </Box>
      </Container>
    </Box>
  );
}
